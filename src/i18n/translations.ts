export const dictionaries: Record<Locale, Dict> = { en, pl, ro };

export const localeLabels: Record<Locale, string> = {
  en: "English",
  pl: "Polski",
  ro: "Română",
};

/** BCP-47 tags used for dates, numbers and text-to-speech. */
export const localeTags: Record<Locale, string> = {
  en: "en-GB",
  pl: "pl-PL",
  ro: "ro-RO",
};

/** English is the primary language, so it is the fallback for every lookup. */
export function translate(locale: Locale, key: string): string {
  return dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? key;
}

export function formatDate(locale: Locale, iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleDateString(localeTags[locale], { day: "2-digit", month: "2-digit", year: "numeric" });
}

export function formatDateTime(locale: Locale, iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleString(localeTags[locale], {
    day: "2-digit",
    month: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  });
}
